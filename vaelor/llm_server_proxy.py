"""The LLM Server auth PROXY: a Vaelor-controlled LAN gate over a loopback model.

**Why a proxy, not engine-level auth (the live-proven pivot).** The GPU AI-Chat
model is served by ``llama-server`` in a container that binds LOOPBACK ONLY
(:mod:`vaelor.gpu_rocmfpx_service` publishes it on ``127.0.0.1:<model-port>`` and
never passes an api key to the engine). Engine-level auth was tried and could not
be trusted: the ROCmFP4 fork's ``llama-server`` does NOT enforce
``--api-key``/``--api-key-file``/``LLAMA_API_KEY`` at all, so a keyed LAN bind was
an UNAUTHENTICATED LAN endpoint. A Vaelor-controlled proxy is the only trustworthy
LAN gate, and it is engine-agnostic: a fork OR a mainline model is exposed
identically and safely, because neither is ever LAN-published.

**The gate.** When the LLM Server is ENABLED, Vaelor runs one small ``nginx``
container in front of the model's loopback endpoint:

* the container is launched by the root hardware bridge (``proxy_start`` /
  ``proxy_stop`` / ``proxy_status``), the same privileged account that launches the
  model container;
* it runs with ``--network host`` so it shares the host network namespace: its
  ``listen`` binds the host's LAN address:port directly, and ``proxy_pass`` reaches
  the model on ``127.0.0.1:<model-port>`` (host loopback). ``--network host`` is
  the approach that WORKS with the model published on ``127.0.0.1``: a model bound
  to loopback is NOT on the docker bridge, so ``--add-host``/``host-gateway`` (which
  resolves to the bridge gateway, e.g. ``172.17.0.1``) could not reach it;
* the config (generated by Vaelor with the current key, written root-owned and
  mounted READ-ONLY) enforces ``Authorization: Bearer <key>``: any request whose
  Authorization header is not exactly ``Bearer <key>`` gets 401, except ``/health``
  (unauthenticated, proxied so it reflects the model). The key lives in the config
  FILE, never on any argv (``docker inspect`` / ``/proc`` are readable to local
  accounts). Buffering is off and the read/send timeouts are long so OpenAI SSE
  streaming works.

**The invariant, now airtight and engine-agnostic.** There is NO way to expose the
model on the LAN except through the running auth proxy, which always has the key:
:func:`_require_keys` refuses to build a proxy launch without a key, and the model
container never binds non-loopback. So enable/disable/rotate all reduce to
starting, stopping, or re-keying this one container.

**The same gate, on a worker (VD-129, the amendment).** A replicated
deployment's worker runs its vLLM replica on loopback and the SAME nginx image
in front of it as :func:`render_gate_config`: the cluster address on the
replica port, the same Bearer check (:func:`bearer_check`, rendered once for
both configs), ``/v1/`` and ``/health`` forwarded to loopback and everything
else answered 404 - because vLLM's own ``--api-key`` was live-probed to gate
only ``/v1`` and leave ``/invocations``, ``/tokenize`` and ``/metrics`` open.
That config is rendered by `GpuPoolRuntime.start_gate` and shipped to the
worker over its transport as a root ``0600`` file; the container is a systemd
unit's foreground process there rather than a bridge-launched daemon, which is
the one difference :func:`proxy_container_command` carries.

**The usage log (ACC-043, ACC-048).** A LAN client's request never passes
through a Vaelor process, so the gate is the one place that can say which key
was used and when. The LLM Server proxy's config (and only that one - the
worker gate, the agent gate and the balancer render none) writes one line per
ADMITTED request into :data:`vaelor.llm_gate_usage.GATE_LOG_FILENAME`, naming
the key by its vault FINGERPRINT, which the config sets inside the branch that
matched that key. The Authorization header is never logged, and a refused
request writes nothing. The directory is a root ``0755`` one under
``/run/vaelor`` that the bridge prepares and refuses to use when it is a link or
not its own (then the gate still serves, without the log, and its status says
so); the bridge rotates the file on its own timer (:mod:`vaelor.llm_gate_log`).
A refused request is written to a separate, separately capped file, so guessing
at keys stays visible and a flood of refusals can never push an admitted line
out of the key log. The control plane reads both (:mod:`vaelor.llm_gate_usage`).
"""

